# =============================================================================
# Markdown reports of scenario results (docs/)
# =============================================================================
# render_scenario_md() turns one saved scenario result into
# docs/scenarios/<id>.md; render_index_md() lists every scenario in
# docs/README.md. Both read only the saved RDS, so the docs can be rebuilt
# without re-running a search (scripts/renderDocs.R).
#
# DEPENDENCIES: R/rootPath.R, R/gridCore.R (best_per_metric).
# =============================================================================

fmt_num <- function(x) sprintf("%.4f", x)
fmt_w   <- function(x) as.character(round(x, 4))
fmt_int <- function(x) format(x, big.mark = ",", scientific = FALSE)
fmt_est <- function(v, se = NULL) {
  if (is.null(se)) fmt_num(v) else paste(fmt_num(v), "\u00b1", fmt_num(se))
}
md_code <- function(x) paste0("`", gsub("|", "\\|", x, fixed = TRUE), "`")
fix_cell <- function(x) ifelse(is.na(x), "free", fmt_w(x))

#' Markdown table from a header and a character matrix (or one row).
md_table <- function(header, rows) {
  rows <- matrix(rows, ncol = length(header))
  c(paste0("| ", paste(header, collapse = " | "), " |"),
    paste0("|", paste(rep("---", length(header)), collapse = "|"), "|"),
    apply(rows, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |")))
}

#' Transition matrix as a table (rows = from, columns = to).
G_table <- function(G, cell = fmt_w) {
  k <- nrow(G)
  H <- paste0("H", seq_len(k))
  cells <- matrix(cell(G), k)
  diag(cells) <- "\u2013"
  md_table(c("from \\ to", H), cbind(H, cells))
}

#' Transition matrix on one line, row by row.
G_rows <- function(G) {
  paste(apply(G, 1, function(z) paste0("(", paste(fmt_w(z), collapse = ", "), ")")),
        collapse = " ")
}

corr_summary <- function(corr, k) {
  if (is.null(corr)) return("independent")
  off <- corr[upper.tri(corr)]
  if (all(off == 0)) return("independent")
  if (length(unique(off)) == 1L) return(paste("equicorrelated, rho =", fmt_w(off[1])))
  sprintf("rho from %s to %s", fmt_w(min(off)), fmt_w(max(off)))
}

constraints_summary <- function(s) {
  x <- c(if (!is.null(s$w_fixed)) "weights", if (!is.null(s$G_fixed)) "transitions")
  if (length(x)) paste(x, collapse = ", ") else "none"
}

#' Re-evaluated estimate (with SE) of metric x, or the search value without
#' re-evaluation.
metric_est <- function(res, df, x) {
  if (is.null(res$validation)) return(fmt_num(df[[x]]))
  fmt_est(df[[paste0(x, "_val")]], df[[paste0(x, "_se")]])
}

#' Kept graphs of metric x in rank order, exact ties (identical search values
#' on every metric) collapsed to their first graph.
#'
#' @return list(rows = data.frame of the first graph per tie group,
#'   ties = group sizes as text, "n+" when the group may extend past top_n)
ranked_groups <- function(res, x) {
  nm  <- res$metrics
  r   <- res$best[order(res$best[[paste0("rank_", x)]], na.last = NA), , drop = FALSE]
  key <- do.call(paste, c(lapply(r[nm], function(z) sprintf("%.12g", z)), sep = "|"))
  grp <- cumsum(c(TRUE, key[-1] != key[-length(key)]))
  n   <- tabulate(grp)
  ties <- as.character(n)
  if (nrow(r) >= res$settings$top_n) ties[length(n)] <- paste0(n[length(n)], "+")
  list(rows = r[!duplicated(grp), , drop = FALSE], ties = ties)
}


#' Markdown page of one scenario result.
#'
#' @param res a saved scenario result (results/<id>/<id>.rds)
#' @return character vector of lines
render_scenario_md <- function(res) {
  m  <- res$meta
  sc <- m$scenario
  s  <- res$settings
  k  <- res$k
  nm <- res$metrics
  v  <- res$validation
  H  <- paste0("H", seq_len(k))
  w_cols <- paste0("w", seq_len(k))
  top1 <- best_per_metric(res)
  link <- function(f) sprintf("[`%s`](../../results/%s/%s)", f, sc$id, f)

  out <- c(
    sprintf("<!-- Generated by scripts/renderDocs.R from results/%s/%s.rds; do not edit by hand. -->",
            sc$id, sc$id),
    "", paste("#", sc$title), "",
    sprintf("- **Scenario:** [`%s`](../../%s)", sc$id, sc$file),
    sprintf("- **Author:** %s", sc$author),
    if (nzchar(sc$date)) sprintf("- **Date:** %s", sc$date),
    sprintf("- **Run:** %s, commit `%s`, R %s, graphicalMCP %s",
            m$run_date, m$git_commit, m$r_version, m$graphicalMCP),
    ""
  )
  if (nzchar(sc$description)) out <- c(out, sc$description, "")
  if (length(m$overrides)) {
    out <- c(out, paste0("> **Note:** run with the command-line overrides ",
                         paste(md_code(m$overrides), collapse = " "),
                         ", so these results do not match the scenario file."), "")
  }

  ## -- Setup ------------------------------------------------------------------
  search_time <- sprintf("search time %.0f s%s", res$search_s,
                         if (!is.null(res$n_shards)) {
                           sprintf(" (summed over %d shards)", res$n_shards)
                         } else "")
  out <- c(out, "## Setup", "",
    sprintf("- %d hypotheses, one-sided alpha = %s, weighted Bonferroni tests",
            k, s$alpha),
    sprintf("- Grid: w_step = %s, g_step = %s, %s candidate graphs",
            s$w_step, s$g_step, fmt_int(res$n_candidates)),
    sprintf("- Search: %s simulations (seed %s), %s",
            fmt_int(s$sim_n), s$seed, search_time),
    if (!is.null(v)) {
      sprintf("- Re-evaluation: %s independent simulations (seed %s), standard errors from %d batch means",
              fmt_int(v$sim_n), v$seed, v$n_batch)
    },
    "", "**Marginal power**", "",
    md_table(c("", H), c("Power", fmt_w(s$mp))),
    "", "**Correlation of the test statistics**", "",
    if (corr_summary(s$corr, k) == "independent") "Independent." else {
      md_table(c("", H), cbind(H, matrix(fmt_w(s$corr), k)))
    },
    "", "**Constraints**", ""
  )
  if (is.null(s$w_fixed) && is.null(s$G_fixed)) {
    out <- c(out, "None: all weights and transitions are searched.", "")
  }
  if (!is.null(s$w_fixed)) {
    out <- c(out, "Weights (free = searched):", "",
             md_table(c("", H), c("Weight", fix_cell(s$w_fixed))), "")
  }
  if (!is.null(s$G_fixed)) {
    out <- c(out, "Transitions (free = searched):", "", G_table(s$G_fixed, fix_cell), "")
  }
  out <- c(out,
    "**Metrics** (maximized; `R` is the simulations x hypotheses rejection matrix)", "",
    md_table(c("Metric", "Definition"), cbind(md_code(nm), md_code(m$metric_defs[nm]))),
    ""
  )

  ## -- Optimal graphs ----------------------------------------------------------
  trade <- vapply(nm, function(x) {
    e <- metric_est(res, top1, x)
    on <- top1$metric == x
    e[on] <- paste0("**", e[on], "**")
    e
  }, character(nrow(top1)))
  out <- c(out, "## Optimal graphs", "",
    if (!is.null(v)) {
      paste("Values are re-evaluated on independent simulations (estimate \u00b1 Monte-Carlo",
            "standard error). The search values used for the ranking are optimistic for the winners.")
    } else "Values are from the search simulations (no re-evaluation).",
    "", "### Trade-off", "",
    "Each row is the graph that is optimal for one metric, evaluated on every metric.", "",
    md_table(c("Optimal for", md_code(nm)), cbind(md_code(top1$metric), trade)),
    ""
  )
  for (i in seq_len(nrow(top1))) {
    ties <- ranked_groups(res, top1$metric[i])$ties[1]
    out <- c(out, sprintf("### `%s`-optimal graph", top1$metric[i]), "",
      md_table(c("", H), c("Weight", fmt_w(unlist(top1[i, w_cols])))), "",
      G_table(top1$G[[i]]), "",
      sprintf("Search values: %s.", paste(
        sprintf("`%s` = %s", nm, fmt_num(unlist(top1[i, nm]))), collapse = ", ")),
      if (ties != "1") {
        sprintf(paste("%s kept graphs give exactly these search values on every metric",
                      "(typically they differ only in transitions that never come into play);",
                      "the first in grid order is shown."),
                ties)
      },
      "")
  }

  ## -- Top graphs per metric ---------------------------------------------------
  n_show <- 10L
  out <- c(out, sprintf("## Top %d per metric", n_show), "",
    paste("Graphs with identical search values on every metric are collapsed into one row;",
          "*Ties* counts them (n+ = may continue beyond the kept graphs).",
          "Transition matrices are given row by row (from H1, H2, ...)."),
    if (!is.null(v)) "Graphs whose values differ by less than about two standard errors are practically equivalent.",
    "")
  for (x in nm) {
    g  <- ranked_groups(res, x)
    sh <- seq_len(min(n_show, nrow(g$rows)))
    r  <- g$rows[sh, , drop = FALSE]
    rows <- cbind(r[[paste0("rank_", x)]], g$ties[sh],
                  apply(as.matrix(r[w_cols]), 1, function(w) paste(fmt_w(w), collapse = ", ")),
                  vapply(r$G, G_rows, character(1)),
                  fmt_num(r[[x]]),
                  if (!is.null(v)) metric_est(res, r, x))
    out <- c(out, sprintf("### `%s`", x), "",
      md_table(c("Rank", "Ties", "w", "G", "Search", if (!is.null(v)) "Re-evaluated"), rows), "")
  }

  ## -- Files -------------------------------------------------------------------
  c(out, "## Files", "",
    sprintf("- %s: best graph per metric", link(paste0(sc$id, "_best.csv"))),
    sprintf("- %s: top %d graphs of every metric; `G` is column-major: `matrix(as.numeric(strsplit(G, \";\")[[1]]), %d)`",
            link(paste0(sc$id, "_top.csv")), s$top_n, k),
    sprintf("- %s: full result, read with `readRDS()`", link(paste0(sc$id, ".rds"))))
}


#' Markdown index of all scenario results.
#'
#' @param all named list of saved scenario results (names = ids)
#' @return character vector of lines
render_index_md <- function(all) {
  ids <- sort(names(all))
  head <- c("<!-- Generated by scripts/renderDocs.R; do not edit by hand. -->", "",
            "# Scenario results", "",
            paste("Optimal multiplicity graphs found by brute-force grid search, one page per",
                  "scenario. To add a scenario, see [CONTRIBUTING.md](../CONTRIBUTING.md)."),
            "")
  if (!length(ids)) return(c(head, "No scenarios yet."))
  rows <- t(vapply(ids, function(id) {
    r  <- all[[id]]
    sc <- r$meta$scenario
    s  <- r$settings
    x  <- r$metrics[1]
    c(sprintf("[%s](scenarios/%s.md)", sc$title, id), sc$author, r$k, s$alpha,
      paste(fmt_w(s$mp), collapse = ", "), corr_summary(s$corr, r$k),
      constraints_summary(s),
      sprintf("`%s` = %s", x, metric_est(r, best_per_metric(r)[1, , drop = FALSE], x)))
  }, character(8)))
  c(head,
    "The last column is the optimum of each scenario's first metric (re-evaluated, \u00b1 MC standard error).",
    "",
    md_table(c("Scenario", "Author", "k", "alpha", "Marginal power", "Correlation",
               "Constraints", "Optimum"), rows))
}


#' Write lines as UTF-8 with LF endings, so docs are identical on every OS.
write_lf <- function(lines, path) {
  writeBin(charToRaw(enc2utf8(paste0(paste(lines, collapse = "\n"), "\n"))), path)
}

#' Rebuild docs/scenarios/<id>.md for the given scenarios and docs/README.md.
#'
#' @param ids scenario ids; NULL = every results/<id>/<id>.rds
gogt_render_docs <- function(ids = NULL) {
  root  <- gogt_root()
  dirs  <- list.dirs(file.path(root, "results"), recursive = FALSE)
  files <- file.path(dirs, paste0(basename(dirs), ".rds"))
  files <- files[file.exists(files)]
  all   <- stats::setNames(lapply(files, readRDS), basename(dirname(files)))
  all   <- all[vapply(all, function(r) !is.null(r$meta$scenario), logical(1))]
  if (is.null(ids)) ids <- names(all)
  miss <- setdiff(ids, names(all))
  if (length(miss)) {
    stop("No scenario results for: ", paste(miss, collapse = ", "),
         " (expected results/<id>/<id>.rds).")
  }
  doc_dir <- file.path(root, "docs", "scenarios")
  dir.create(doc_dir, recursive = TRUE, showWarnings = FALSE)
  for (id in ids) {
    write_lf(render_scenario_md(all[[id]]), file.path(doc_dir, paste0(id, ".md")))
  }
  write_lf(render_index_md(all), file.path(root, "docs", "README.md"))
  cat(sprintf("[docs] rendered %d scenario page(s) and docs/README.md (%d scenarios)\n",
              length(ids), length(all)))
  invisible(ids)
}
